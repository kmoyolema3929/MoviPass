-- ======================================================================
-- Cambio 9: catálogos de la aplicación
--
--  * provincias y cantones del Ecuador (división político-administrativa
--    oficial CONALI/INEC: 24 provincias y 221 cantones; las "zonas no
--    delimitadas" no son cantones y no se incluyen). Los id son los
--    códigos INEC, así la carga es igual en cualquier base.
--  * marcas_carroceria y marcas_chasis.
--  * tipos_pasajero: solo si la tabla ya existe (en algunas bases no está),
--    se agrega "activo", la lectura pública y la escritura del administrador.
--    Esta migración no la crea.
--
-- Reglas:
--  * Nombres únicos sin importar mayúsculas (en cantones, dentro de cada
--    provincia). El orden alfabético se pide al leer (order by nombre);
--    los índices únicos sobre lower(nombre) también aceleran esa consulta.
--  * RLS: cualquiera lee (también sin sesión, para el buscador público);
--    solo el administrador inserta, edita o borra.
--  * Se puede ejecutar varias veces: if not exists / on conflict do nothing.
-- ======================================================================

begin;

-- ======================================================================
-- 1. Tablas
-- ======================================================================
create table if not exists public.provincias (
  id smallint primary key,
  nombre varchar(60) not null check (btrim(nombre) <> ''),
  activo boolean not null default true
);

create unique index if not exists provincias_nombre_unico
  on public.provincias (lower(nombre));

create table if not exists public.cantones (
  id smallint primary key,
  provincia_id smallint not null references public.provincias(id),
  nombre varchar(80) not null check (btrim(nombre) <> ''),
  activo boolean not null default true
);

-- Hay cantones con el mismo nombre en provincias distintas
-- (Bolívar en Carchi y Manabí, Olmedo en Loja y Manabí).
create unique index if not exists cantones_nombre_unico_por_provincia
  on public.cantones (provincia_id, lower(nombre));

create index if not exists cantones_nombre_idx
  on public.cantones (lower(nombre));

create table if not exists public.marcas_carroceria (
  id integer generated by default as identity primary key,
  nombre varchar(60) not null check (btrim(nombre) <> ''),
  activo boolean not null default true
);

create unique index if not exists marcas_carroceria_nombre_unico
  on public.marcas_carroceria (lower(nombre));

create table if not exists public.marcas_chasis (
  id integer generated by default as identity primary key,
  nombre varchar(60) not null check (btrim(nombre) <> ''),
  activo boolean not null default true
);

create unique index if not exists marcas_chasis_nombre_unico
  on public.marcas_chasis (lower(nombre));

