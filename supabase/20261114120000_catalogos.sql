-- 3. Permisos y RLS de los catálogos nuevos
-- ======================================================================
alter table public.provincias enable row level security;
alter table public.cantones enable row level security;
alter table public.marcas_carroceria enable row level security;
alter table public.marcas_chasis enable row level security;

revoke all on table
  public.provincias, public.cantones,
  public.marcas_carroceria, public.marcas_chasis
  from public, anon, authenticated;

grant select on table
  public.provincias, public.cantones,
  public.marcas_carroceria, public.marcas_chasis
  to anon, authenticated;

grant insert, update, delete on table
  public.provincias, public.cantones,
  public.marcas_carroceria, public.marcas_chasis
  to authenticated;

-- Mismas políticas para los cuatro catálogos nuevos.
do $$
declare
  tabla text;
begin
  foreach tabla in array array[
    'provincias', 'cantones', 'marcas_carroceria', 'marcas_chasis'
  ] loop
    execute format('drop policy if exists "lectura publica de %1$s" on public.%1$I', tabla);
    execute format('drop policy if exists "administrador crea %1$s" on public.%1$I', tabla);
    execute format('drop policy if exists "administrador edita %1$s" on public.%1$I', tabla);
    execute format('drop policy if exists "administrador elimina %1$s" on public.%1$I', tabla);

    execute format(
      'create policy "lectura publica de %1$s" on public.%1$I
         for select to anon, authenticated
         using (true)', tabla);

    execute format(
      'create policy "administrador crea %1$s" on public.%1$I
         for insert to authenticated
         with check ((select public.rol_actual()) = ''administrador'')', tabla);

    execute format(
      'create policy "administrador edita %1$s" on public.%1$I
         for update to authenticated
         using ((select public.rol_actual()) = ''administrador'')
         with check ((select public.rol_actual()) = ''administrador'')', tabla);

    execute format(
      'create policy "administrador elimina %1$s" on public.%1$I
         for delete to authenticated
         using ((select public.rol_actual()) = ''administrador'')', tabla);
  end loop;
end
$$;

-- ======================================================================
-- 4. tipos_pasajero: solo si la tabla existe (no se crea aquí)
--    Se usa SQL dinámico para que la migración compile aunque no exista.
-- ======================================================================
do $$
begin
  if to_regclass('public.tipos_pasajero') is null then
    raise notice 'public.tipos_pasajero no existe: se omiten sus cambios';
    return;
  end if;

  execute 'alter table public.tipos_pasajero
             add column if not exists activo boolean not null default true';

  -- Los datos vienen de 20261104000100_compras_boletos_pagos.sql.
  -- Solo se reponen si faltan; no se pisa un descuento ya ajustado.
  execute $sql$
    insert into public.tipos_pasajero (codigo, nombre, descuento) values
      ('normal', 'Adulto', 0),
      ('nino', 'Niño', 50),
      ('tercera_edad', 'Tercera edad', 50)
    on conflict do nothing
  $sql$;

  execute 'alter table public.tipos_pasajero enable row level security';
  execute 'revoke all on table public.tipos_pasajero from public, anon, authenticated';
  execute 'grant select on table public.tipos_pasajero to anon, authenticated';
  execute 'grant insert, update, delete on table public.tipos_pasajero to authenticated';

  -- La política anterior solo dejaba leer con sesión.
  execute 'drop policy if exists "lectura de tipos de pasajero" on public.tipos_pasajero';
  execute 'drop policy if exists "lectura publica de tipos_pasajero" on public.tipos_pasajero';
  execute 'drop policy if exists "administrador crea tipos_pasajero" on public.tipos_pasajero';
  execute 'drop policy if exists "administrador edita tipos_pasajero" on public.tipos_pasajero';
  execute 'drop policy if exists "administrador elimina tipos_pasajero" on public.tipos_pasajero';

  execute 'create policy "lectura publica de tipos_pasajero" on public.tipos_pasajero
             for select to anon, authenticated
             using (true)';

  execute $sql$
    create policy "administrador crea tipos_pasajero" on public.tipos_pasajero
      for insert to authenticated
      with check ((select public.rol_actual()) = 'administrador')
  $sql$;

  execute $sql$
    create policy "administrador edita tipos_pasajero" on public.tipos_pasajero
      for update to authenticated
      using ((select public.rol_actual()) = 'administrador')
      with check ((select public.rol_actual()) = 'administrador')
  $sql$;

  execute $sql$
    create policy "administrador elimina tipos_pasajero" on public.tipos_pasajero
      for delete to authenticated
      using ((select public.rol_actual()) = 'administrador')
  $sql$;
end
$$;

