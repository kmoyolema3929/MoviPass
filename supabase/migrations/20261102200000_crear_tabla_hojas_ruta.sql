-- Crear tabla de hojas_ruta
CREATE TABLE IF NOT EXISTS public.hojas_ruta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    frecuencia_id BIGINT REFERENCES public.frecuencias(id) ON DELETE CASCADE NOT NULL,
    bus_id BIGINT REFERENCES public.buses(id) ON DELETE CASCADE NOT NULL,
    fecha DATE NOT NULL,
    estado VARCHAR(50) DEFAULT 'Programado' NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Habilitar Row Level Security (RLS)
ALTER TABLE public.hojas_ruta ENABLE ROW LEVEL SECURITY;

-- Políticas de Seguridad RLS por rol
CREATE POLICY "Permitir lectura publica de hojas_ruta" 
ON public.hojas_ruta FOR SELECT 
USING (true);

CREATE POLICY "Permitir insercion a usuarios autenticados en hojas_ruta" 
ON public.hojas_ruta FOR INSERT 
WITH CHECK (auth.role() = 'authenticated');

CREATE POLICY "Permitir actualizacion a usuarios autenticados en hojas_ruta" 
ON public.hojas_ruta FOR UPDATE 
USING (auth.role() = 'authenticated');

CREATE POLICY "Permitir eliminacion a usuarios autenticados en hojas_ruta" 
ON public.hojas_ruta FOR DELETE 
USING (auth.role() = 'authenticated');