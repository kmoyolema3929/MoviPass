-- Crear tabla de frecuencias
CREATE TABLE IF NOT EXISTS public.frecuencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origen VARCHAR(100) NOT NULL,
    destino VARCHAR(100) NOT NULL,
    hora TIME NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Habilitar Row Level Security (RLS)
ALTER TABLE public.frecuencias ENABLE ROW LEVEL SECURITY;

-- Políticas de Seguridad RLS
CREATE POLICY "Permitir lectura publica de frecuencias" 
ON public.frecuencias FOR SELECT 
USING (true);

CREATE POLICY "Permitir insercion a usuarios autenticados" 
ON public.frecuencias FOR INSERT 
WITH CHECK (true);

CREATE POLICY "Permitir actualizacion a usuarios autenticados" 
ON public.frecuencias FOR UPDATE 
USING (true);

CREATE POLICY "Permitir eliminacion a usuarios autenticados" 
ON public.frecuencias FOR DELETE 
USING (true);