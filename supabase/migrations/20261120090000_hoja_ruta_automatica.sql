-- =====================================================================
-- Cambio 7, parte 7.2: hoja de ruta automática
--
-- Qué cambia:
--   1. Tabla hojas_ruta_paradas: los buses del grupo que un día no hacen
--      frecuencia: Parada 1 = descanso (uno o más) y Parada 2 = retén (uno).
--      Un bus no puede estar el mismo día en una frecuencia y en una parada.
--   2. generar_hoja_ruta(grupo, desde, hasta): rotación cíclica en diagonal
--      (cada día cada bus baja una fila; el del retén sube a la primera
--      frecuencia), por grupo, sin huecos y en el orden de las frecuencias.
--        - Flota mínima: buses del grupo con plantilla >= frecuencias activas + 2.
--        - Continúa desde el último día generado (no empieza de nuevo).
--        - Solo desde hoy y hasta 14 días (fecha de Ecuador); no toca días pasados.
--        - Un día con boletos vendidos no se regenera: se conserva y la rotación
--          sigue desde él; el resultado dice cuántos boletos tiene.
--      Es la misma regla que frontend/js/rotacion.js (con pruebas).
--   3. reemplazar_con_reten: cambia el bus de una frecuencia por el del retén
--      (el que sale pasa al retén). Con boletos vendidos, solo si todos esos
--      asientos existen y no están bloqueados en el bus del retén.
--   4. borrar_dia_hoja_ruta (sin boletos), obtener_hoja_ruta y
--      resumen_grupo_hoja_ruta para la pantalla.
--   5. El gerente y el oficinista de la cooperativa pueden generar y
--      administrar las hojas de ruta (y ven lo que hizo el otro).
-- Parte de la base en la nube (cambio7-base-nube.txt).
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- 1. Paradas del día (descanso y retén)
-- ---------------------------------------------------------------------
create table if not exists public.hojas_ruta_paradas (
    id bigint generated by default as identity primary key,
    grupo_id uuid not null references public.grupos_bus (id) on delete cascade,
    fecha date not null,
    bus_id uuid not null references public.buses (id) on delete restrict,
    tipo varchar(10) not null check (tipo in ('descanso', 'reten')),
    posicion smallint not null check (posicion >= 1),
    creado_en timestamptz not null default now(),
    constraint hojas_ruta_paradas_bus_fecha_unique unique (bus_id, fecha),
    constraint hojas_ruta_paradas_posicion_unique unique (grupo_id, fecha, tipo, posicion)
);

create index if not exists hojas_ruta_paradas_grupo_fecha_idx on public.hojas_ruta_paradas (grupo_id, fecha);

-- ---------------------------------------------------------------------
-- 2. Permisos: administrador, gerente u oficinista de la cooperativa
-- ---------------------------------------------------------------------
create or replace function public.puede_gestionar_hoja_ruta(p_cooperativa_id uuid)
returns boolean
language sql
stable
security definer
set search_path to ''
as $function$
    select public.rol_actual() = 'administrador'
        or (public.rol_actual() in ('cooperativa', 'oficinista') and public.es_de_mi_cooperativa(p_cooperativa_id));
$function$;

-- Devuelve la cooperativa del grupo; error si no existe o no hay permiso.
create or replace function public.exigir_gestor_de_hoja_ruta(p_grupo_id uuid)
returns uuid
language plpgsql
stable
security definer
set search_path to ''
as $function$
declare
    v_cooperativa uuid;
begin
    select g.cooperativa_id into v_cooperativa
    from public.grupos_bus as g
    where g.id = p_grupo_id;

    if v_cooperativa is null then
        raise exception 'El grupo de bus no existe. Recarga la página.' using errcode = '40001';
    end if;

    if not public.puede_gestionar_hoja_ruta(v_cooperativa) then
        raise exception 'No tienes permiso para gestionar la hoja de ruta de esta cooperativa.' using errcode = '42501';
    end if;

    return v_cooperativa;
end;
$function$;

alter table public.hojas_ruta_paradas enable row level security;
revoke all on table public.hojas_ruta_paradas from anon;
grant select on table public.hojas_ruta_paradas to authenticated;

drop policy if exists "hojas_ruta_paradas lectura" on public.hojas_ruta_paradas;
create policy "hojas_ruta_paradas lectura"
    on public.hojas_ruta_paradas
    for select
    to authenticated
    using (
        exists (
            select 1 from public.grupos_bus as g
            where g.id = hojas_ruta_paradas.grupo_id
              and public.puede_gestionar_hoja_ruta(g.cooperativa_id)
        )
    );

-- El oficinista también puede escribir en hojas_ruta (antes solo el gerente
-- y el administrador). Mismas condiciones que las políticas de la nube.
drop policy if exists "crear hojas de ruta autorizadas" on public.hojas_ruta;
create policy "crear hojas de ruta autorizadas"
    on public.hojas_ruta
    for insert
    to authenticated
    with check (
        (select public.rol_actual()) = 'administrador'
        or (
            (select public.rol_actual()) in ('cooperativa', 'oficinista')
            and exists (
                select 1
                from public.buses as b
                join public.cooperativas_usuarios as asignacion on asignacion.cooperativa_id = b.cooperativa_id
                where b.id = hojas_ruta.bus_id
                  and asignacion.perfil_id = (select auth.uid())
            )
        )
    );

drop policy if exists "editar hojas de ruta autorizadas" on public.hojas_ruta;
create policy "editar hojas de ruta autorizadas"
    on public.hojas_ruta
    for update
    to authenticated
    using (
        (select public.rol_actual()) = 'administrador'
        or (
            (select public.rol_actual()) in ('cooperativa', 'oficinista')
            and exists (
                select 1
                from public.buses as b
                join public.cooperativas_usuarios as asignacion on asignacion.cooperativa_id = b.cooperativa_id
                where b.id = hojas_ruta.bus_id
                  and asignacion.perfil_id = (select auth.uid())
            )
        )
    )
    with check (
        (select public.rol_actual()) = 'administrador'
        or (
            (select public.rol_actual()) in ('cooperativa', 'oficinista')
            and exists (
                select 1
                from public.buses as b
                join public.cooperativas_usuarios as asignacion on asignacion.cooperativa_id = b.cooperativa_id
                where b.id = hojas_ruta.bus_id
                  and asignacion.perfil_id = (select auth.uid())
            )
        )
    );

drop policy if exists "eliminar hojas de ruta autorizadas" on public.hojas_ruta;
create policy "eliminar hojas de ruta autorizadas"
    on public.hojas_ruta
    for delete
    to authenticated
    using (
        (select public.rol_actual()) = 'administrador'
        or (
            (select public.rol_actual()) in ('cooperativa', 'oficinista')
            and exists (
                select 1
                from public.buses as b
                join public.cooperativas_usuarios as asignacion on asignacion.cooperativa_id = b.cooperativa_id
                where b.id = hojas_ruta.bus_id
                  and asignacion.perfil_id = (select auth.uid())
            )
        )
    );

-- ---------------------------------------------------------------------
-- 3. Un bus no hace dos cosas el mismo día (frecuencia y parada)
--    El intercambio con el retén lo permite por un instante.
-- ---------------------------------------------------------------------
create or replace function public.exigir_bus_sin_parada()
returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
begin
    if coalesce(current_setting('movipass.intercambio_reten', true), '') <> 'si'
       and exists (
           select 1 from public.hojas_ruta_paradas as p
           where p.bus_id = new.bus_id and p.fecha = new.fecha
       ) then
        raise exception 'Ese bus ya está en descanso o de retén ese día.' using errcode = '23505';
    end if;

    return new;
end;
$function$;

drop trigger if exists hojas_ruta_bus_sin_parada on public.hojas_ruta;
create trigger hojas_ruta_bus_sin_parada
    before insert or update of bus_id, fecha
    on public.hojas_ruta
    for each row
    execute function public.exigir_bus_sin_parada();

create or replace function public.validar_parada_hoja_ruta()
returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
declare
    v_hoy date := (now() at time zone 'America/Guayaquil')::date;
begin
    if tg_op = 'INSERT' and (new.fecha < v_hoy or new.fecha > v_hoy + 14) then
        raise exception 'Solo se puede programar desde hoy y hasta 14 días.' using errcode = '23514';
    end if;

    if tg_op = 'UPDATE' and old.fecha < v_hoy then
        raise exception 'No se puede cambiar un día pasado.' using errcode = '23514';
    end if;

    if not exists (
        select 1 from public.buses as b
        where b.id = new.bus_id and b.grupo_id = new.grupo_id
    ) then
        raise exception 'El bus no pertenece al grupo de la hoja de ruta.' using errcode = '23514';
    end if;

    if coalesce(current_setting('movipass.intercambio_reten', true), '') <> 'si'
       and exists (
           select 1 from public.hojas_ruta as h
           where h.bus_id = new.bus_id and h.fecha = new.fecha
       ) then
        raise exception 'Ese bus ya tiene un turno ese día.' using errcode = '23505';
    end if;

    return new;
end;
$function$;

drop trigger if exists hojas_ruta_paradas_validar on public.hojas_ruta_paradas;
create trigger hojas_ruta_paradas_validar
    before insert or update
    on public.hojas_ruta_paradas
    for each row
    execute function public.validar_parada_hoja_ruta();

-- ---------------------------------------------------------------------
-- 4. Orden de los buses de un día del grupo: frecuencias (en su orden),
--    descanso y retén. Vacío si el día no está generado.
-- ---------------------------------------------------------------------
create or replace function public.orden_dia_hoja_ruta(p_grupo_id uuid, p_fecha date)
returns uuid[]
language sql
stable
security definer
set search_path to ''
as $function$
    select coalesce(array_agg(x.bus_id order by x.bloque, x.posicion), '{}')
    from (
        select h.bus_id, 0 as bloque,
               row_number() over (order by f.orden_hoja_ruta nulls last, f.hora, f.id) as posicion
        from public.hojas_ruta as h
        join public.frecuencias as f on f.id = h.frecuencia_id
        where f.grupo_id = p_grupo_id and h.fecha = p_fecha
        union all
        select p.bus_id, case p.tipo when 'descanso' then 1 else 2 end, p.posicion
        from public.hojas_ruta_paradas as p
        where p.grupo_id = p_grupo_id and p.fecha = p_fecha
    ) as x;
$function$;

-- Boletos vendidos un día en los viajes del grupo (sus frecuencias o sus buses).
create or replace function public.boletos_dia_hoja_ruta(p_grupo_id uuid, p_fecha date)
returns int
language sql
stable
security definer
set search_path to ''
as $function$
    select count(*)::int
    from public.boletos as bo
    join public.viajes as v on v.id = bo.viaje_id
    where v.fecha = p_fecha
      and (
          v.frecuencia_id in (select f.id from public.frecuencias as f where f.grupo_id = p_grupo_id)
          or v.bus_id in (select b.id from public.buses as b where b.grupo_id = p_grupo_id)
      );
$function$;

-- ---------------------------------------------------------------------
-- 5. Generar la hoja de ruta de un grupo
-- ---------------------------------------------------------------------
create or replace function public.generar_hoja_ruta(p_grupo_id uuid, p_desde date, p_hasta date)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
    v_hoy date := (now() at time zone 'America/Guayaquil')::date;
    v_frecuencias bigint[];
    v_todas_frecuencias bigint[];
    v_buses uuid[];
    v_todos_buses uuid[];
    v_f int;
    v_b int;
    v_orden uuid[];
    v_ultimo date;
    v_seq uuid[];
    v_k int;
    v_dia date;
    v_boletos int;
    v_existente uuid[];
    v_i int;
    v_generados jsonb := '[]'::jsonb;
    v_conservados jsonb := '[]'::jsonb;
begin
    perform public.exigir_gestor_de_hoja_ruta(p_grupo_id);

    -- Un grupo se genera de a uno (evita dos generaciones a la vez).
    perform 1 from public.grupos_bus as g where g.id = p_grupo_id for update;

    if p_desde is null or p_hasta is null or p_hasta < p_desde then
        raise exception 'Elige un rango de fechas válido.' using errcode = '22023';
    end if;

    if p_desde < v_hoy then
        raise exception 'No se pueden generar días pasados (hoy es %).', to_char(v_hoy, 'DD/MM/YYYY') using errcode = '23514';
    end if;

    if p_hasta > v_hoy + 14 then
        raise exception 'Solo se puede generar hasta 14 días de anticipación (hasta el %).', to_char(v_hoy + 14, 'DD/MM/YYYY')
            using errcode = '23514';
    end if;

    -- Frecuencias activas del grupo, en el orden de la hoja de ruta.
    select coalesce(array_agg(f.id order by f.orden_hoja_ruta nulls last, f.hora, f.id), '{}')
      into v_frecuencias
    from public.frecuencias as f
    where f.grupo_id = p_grupo_id and f.activa;

    select coalesce(array_agg(f.id), '{}') into v_todas_frecuencias
    from public.frecuencias as f where f.grupo_id = p_grupo_id;

    -- Buses del grupo con plantilla, por número interno (numérico si lo es).
    select coalesce(array_agg(b.id order by substring(b.numero_interno from '^[0-9]+')::int nulls last, b.numero_interno), '{}')
      into v_buses
    from public.buses as b
    where b.grupo_id = p_grupo_id and b.plantilla_id is not null;

    select coalesce(array_agg(b.id), '{}') into v_todos_buses
    from public.buses as b where b.grupo_id = p_grupo_id;

    v_f := cardinality(v_frecuencias);
    v_b := cardinality(v_buses);

    if v_f = 0 then
        raise exception 'El grupo no tiene frecuencias activas.' using errcode = '23514';
    end if;

    if v_b < v_f + 2 then
        raise exception 'Faltan % %: el grupo tiene % % con plantilla y % % activa%; se necesitan al menos % (frecuencias + descanso + retén).',
            v_f + 2 - v_b, case when v_f + 2 - v_b = 1 then 'bus' else 'buses' end,
            v_b, case when v_b = 1 then 'bus' else 'buses' end,
            v_f, case when v_f = 1 then 'frecuencia' else 'frecuencias' end, case when v_f = 1 then '' else 's' end,
            v_f + 2
            using errcode = '23514';
    end if;

    -- Último día ya generado antes del rango: la rotación continúa desde él.
    select max(x.fecha) into v_ultimo
    from (
        select h.fecha from public.hojas_ruta as h
        where h.frecuencia_id = any (v_todas_frecuencias) and h.fecha < p_desde
        union all
        select p.fecha from public.hojas_ruta_paradas as p
        where p.grupo_id = p_grupo_id and p.fecha < p_desde
    ) as x;

    if v_ultimo is not null then
        v_orden := public.orden_dia_hoja_ruta(p_grupo_id, v_ultimo);
    end if;

    for v_dia in select d::date from generate_series(p_desde, p_hasta, interval '1 day') as d loop
        v_boletos := public.boletos_dia_hoja_ruta(p_grupo_id, v_dia);

        -- Día con boletos: se conserva y la rotación sigue desde él.
        if v_boletos > 0 then
            v_conservados := v_conservados || jsonb_build_object('fecha', v_dia, 'boletos', v_boletos);
            v_existente := public.orden_dia_hoja_ruta(p_grupo_id, v_dia);

            if cardinality(v_existente) > 0 then
                v_orden := v_existente;
                v_ultimo := v_dia;
            end if;

            continue;
        end if;

        -- Orden del día: inicial, o el anterior (sin los que salieron, con los
        -- nuevos al final) rotado un día por cada día de diferencia.
        if v_orden is null or cardinality(v_orden) = 0 then
            v_seq := v_buses;
        else
            v_seq := array(
                select u.id from unnest(v_orden) with ordinality as u(id, n)
                where u.id = any (v_buses) order by u.n
            ) || array(
                select u.id from unnest(v_buses) with ordinality as u(id, n)
                where not (u.id = any (v_orden)) order by u.n
            );

            v_k := (v_dia - v_ultimo) % v_b;

            if v_k > 0 then
                v_seq := v_seq[v_b - v_k + 1 : v_b] || v_seq[1 : v_b - v_k];
            end if;
        end if;

        -- Se rehace el día (sin boletos): hojas del grupo (con sus viajes) y paradas.
        delete from public.hojas_ruta as h
        where h.fecha = v_dia
          and (h.frecuencia_id = any (v_todas_frecuencias) or h.bus_id = any (v_todos_buses));

        delete from public.hojas_ruta_paradas as p
        where p.fecha = v_dia
          and (p.grupo_id = p_grupo_id or p.bus_id = any (v_todos_buses));

        for v_i in 1..v_f loop
            insert into public.hojas_ruta (frecuencia_id, bus_id, fecha)
            values (v_frecuencias[v_i], v_seq[v_i], v_dia);
        end loop;

        for v_i in (v_f + 1)..(v_b - 1) loop
            insert into public.hojas_ruta_paradas (grupo_id, fecha, bus_id, tipo, posicion)
            values (p_grupo_id, v_dia, v_seq[v_i], 'descanso', v_i - v_f);
        end loop;

        insert into public.hojas_ruta_paradas (grupo_id, fecha, bus_id, tipo, posicion)
        values (p_grupo_id, v_dia, v_seq[v_b], 'reten', 1);

        v_generados := v_generados || to_jsonb(v_dia);
        v_orden := v_seq;
        v_ultimo := v_dia;
    end loop;

    return jsonb_build_object('generados', v_generados, 'conservados', v_conservados);
exception
    when unique_violation then
        raise exception 'Un bus del grupo ya tiene otro turno en esos días (por ejemplo en otra frecuencia). Revisa la hoja de ruta. Detalle: %', sqlerrm
            using errcode = '23505';
end;
$function$;

-- ---------------------------------------------------------------------
-- 6. Reemplazo rápido: el bus del retén toma la frecuencia
-- ---------------------------------------------------------------------
create or replace function public.reemplazar_con_reten(p_hoja_ruta_id bigint)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
    v_hoy date := (now() at time zone 'America/Guayaquil')::date;
    v_hoja public.hojas_ruta%rowtype;
    v_grupo uuid;
    v_reten public.hojas_ruta_paradas%rowtype;
    v_faltan text;
begin
    select h.* into v_hoja from public.hojas_ruta as h where h.id = p_hoja_ruta_id for update;

    if not found then
        raise exception 'Ese turno ya no existe. Recarga la página.' using errcode = '40001';
    end if;

    select f.grupo_id into v_grupo from public.frecuencias as f where f.id = v_hoja.frecuencia_id;
    perform public.exigir_gestor_de_hoja_ruta(v_grupo);

    if v_hoja.fecha < v_hoy then
        raise exception 'No se puede cambiar un día pasado.' using errcode = '23514';
    end if;

    select p.* into v_reten
    from public.hojas_ruta_paradas as p
    where p.grupo_id = v_grupo and p.fecha = v_hoja.fecha and p.tipo = 'reten'
    for update;

    if not found then
        raise exception 'Ese día no tiene bus de retén.' using errcode = '23514';
    end if;

    -- Boletos vendidos: sus asientos deben existir (y no estar bloqueados) en el bus del retén.
    select string_agg(distinct bo.numero_asiento::text, ', ')
      into v_faltan
    from public.boletos as bo
    join public.viajes as v on v.id = bo.viaje_id
    where v.hoja_ruta_id = v_hoja.id
      and bo.estado in ('reservado', 'emitido')
      and not exists (
          select 1
          from public.buses as br
          join public.plantilla_asientos as pa on pa.plantilla_id = br.plantilla_id
          where br.id = v_reten.bus_id
            and pa.numero = bo.numero_asiento
            and pa.tipo <> 'bloqueado'
      );

    if v_faltan is not null then
        raise exception 'No se puede usar el retén: los asientos vendidos % no existen o están bloqueados en el bus del retén.', v_faltan
            using errcode = '55006';
    end if;

    perform set_config('movipass.intercambio_reten', 'si', true);

    update public.hojas_ruta set bus_id = v_reten.bus_id where id = v_hoja.id;
    update public.hojas_ruta_paradas set bus_id = v_hoja.bus_id where id = v_reten.id;

    perform set_config('movipass.intercambio_reten', '', true);

    return jsonb_build_object('bus_frecuencia', v_reten.bus_id, 'bus_reten', v_hoja.bus_id);
end;
$function$;

-- ---------------------------------------------------------------------
-- 7. Borrar un día (sin boletos)
-- ---------------------------------------------------------------------
create or replace function public.borrar_dia_hoja_ruta(p_grupo_id uuid, p_fecha date)
returns void
language plpgsql
security definer
set search_path to ''
as $function$
declare
    v_boletos int;
begin
    perform public.exigir_gestor_de_hoja_ruta(p_grupo_id);

    if p_fecha < (now() at time zone 'America/Guayaquil')::date then
        raise exception 'No se puede borrar un día pasado.' using errcode = '23514';
    end if;

    v_boletos := public.boletos_dia_hoja_ruta(p_grupo_id, p_fecha);

    if v_boletos > 0 then
        raise exception 'El % tiene % vendido%: no se puede borrar.', to_char(p_fecha, 'DD/MM/YYYY'),
            case when v_boletos = 1 then '1 boleto' else v_boletos || ' boletos' end,
            case when v_boletos = 1 then '' else 's' end
            using errcode = '23503';
    end if;

    delete from public.hojas_ruta as h
    where h.fecha = p_fecha
      and h.frecuencia_id in (select f.id from public.frecuencias as f where f.grupo_id = p_grupo_id);

    delete from public.hojas_ruta_paradas as p
    where p.grupo_id = p_grupo_id and p.fecha = p_fecha;
end;
$function$;

-- ---------------------------------------------------------------------
-- 8. Lectura para la pantalla (gerente y oficinista ven lo mismo)
-- ---------------------------------------------------------------------
create or replace function public.obtener_hoja_ruta(p_grupo_id uuid, p_desde date, p_hasta date)
returns table (
    fecha date, tipo text, frecuencia_id bigint, posicion int, hoja_ruta_id bigint,
    bus_id uuid, numero_interno text, placa text, boletos int
)
language plpgsql
stable
security definer
set search_path to ''
as $function$
begin
    perform public.exigir_gestor_de_hoja_ruta(p_grupo_id);

    return query
    select h.fecha, 'frecuencia'::text, h.frecuencia_id, null::int, h.id, h.bus_id,
           b.numero_interno::text, b.placa::text,
           (select count(*)::int from public.boletos as bo join public.viajes as v on v.id = bo.viaje_id
            where v.hoja_ruta_id = h.id and bo.estado in ('reservado', 'emitido'))
    from public.hojas_ruta as h
    join public.frecuencias as f on f.id = h.frecuencia_id
    join public.buses as b on b.id = h.bus_id
    where f.grupo_id = p_grupo_id and h.fecha between p_desde and p_hasta
    union all
    select p.fecha, p.tipo::text, null::bigint, p.posicion::int, null::bigint, p.bus_id,
           b.numero_interno::text, b.placa::text, 0
    from public.hojas_ruta_paradas as p
    join public.buses as b on b.id = p.bus_id
    where p.grupo_id = p_grupo_id and p.fecha between p_desde and p_hasta;
end;
$function$;

create or replace function public.resumen_grupo_hoja_ruta(p_grupo_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path to ''
as $function$
begin
    perform public.exigir_gestor_de_hoja_ruta(p_grupo_id);

    return jsonb_build_object(
        'frecuencias', coalesce((
            select jsonb_agg(jsonb_build_object(
                'id', f.id, 'origen', f.origen, 'destino', f.destino, 'hora', f.hora,
                'activa', f.activa, 'orden_hoja_ruta', f.orden_hoja_ruta
            ) order by f.orden_hoja_ruta nulls last, f.hora, f.id)
            from public.frecuencias as f where f.grupo_id = p_grupo_id
        ), '[]'::jsonb),
        'buses', coalesce((
            select jsonb_agg(jsonb_build_object(
                'id', b.id, 'numero_interno', b.numero_interno, 'placa', b.placa,
                'con_plantilla', b.plantilla_id is not null
            ) order by substring(b.numero_interno from '^[0-9]+')::int nulls last, b.numero_interno)
            from public.buses as b where b.grupo_id = p_grupo_id
        ), '[]'::jsonb)
    );
end;
$function$;

